CREATE TABLE CONTACT_TYPE (
	ID INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	NAME VARCHAR(100) CHARACTER SET WIN1251 NOT NULL,
	CONSTRAINT CONTACT_TYPE_PK PRIMARY KEY (ID),
	CONSTRAINT CONTACT_TYPE_UNIQUE UNIQUE (NAME)
);
COMMENT ON COLUMN CONTACT_TYPE.ID IS 'ID типа контакта';
COMMENT ON COLUMN CONTACT_TYPE.NAME IS 'Содержимое контакта';


CREATE TABLE PERSON (
	ID INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	SURNAME VARCHAR(100) CHARACTER SET WIN1251 NOT NULL,
	NAME VARCHAR(100) CHARACTER SET WIN1251 NOT NULL,
	SECOND_NAME VARCHAR(100) CHARACTER SET WIN1251,
	SEX BOOLEAN DEFAULT True NOT NULL,
	DOB DATE NOT NULL,
	CONSTRAINT PERSON_PK PRIMARY KEY (ID),
	CONSTRAINT PERSON_UNIQUE UNIQUE (SURNAME,NAME,SECOND_NAME,SEX,DOB)
);
COMMENT ON COLUMN PERSON.ID IS 'ID персоны';
COMMENT ON COLUMN PERSON.SURNAME IS 'Фамилия';
COMMENT ON COLUMN PERSON.NAME IS 'Имя';
COMMENT ON COLUMN PERSON.SECOND_NAME IS 'Отчество';
COMMENT ON COLUMN PERSON.SEX IS 'Пол';
COMMENT ON COLUMN PERSON.DOB IS 'Дата рождения';


CREATE TABLE CONTACT (
	ID INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	VAL VARCHAR(100) CHARACTER SET WIN1251 NOT NULL,
	PERSON_ID INTEGER NOT NULL,
	CONTACT_TYPE_ID INTEGER NOT NULL,
	CONSTRAINT CONTACT_PK PRIMARY KEY (ID),
	CONSTRAINT CONTACT_UNIQUE UNIQUE (VAL,PERSON_ID,CONTACT_TYPE_ID),
	CONSTRAINT CONTACT_CONTACT_TYPE_FK FOREIGN KEY (CONTACT_TYPE_ID) REFERENCES CONTACT_TYPE(ID),
	CONSTRAINT CONTACT_PERSON_FK FOREIGN KEY (PERSON_ID) REFERENCES PERSON(ID) ON DELETE CASCADE ON UPDATE CASCADE
);
COMMENT ON COLUMN CONTACT.ID IS 'ID контакта';
COMMENT ON COLUMN CONTACT.VAL IS 'Содержимое контакта';
COMMENT ON COLUMN CONTACT.PERSON_ID IS 'Внешний ключ к PERSON';
COMMENT ON COLUMN CONTACT.CONTACT_TYPE_ID IS 'Внешний ключ к CONTACT_TYPE';


SET TERM ^ ;


CREATE OR ALTER PROCEDURE SP_GET_PERSONS (
	P_SEX BOOLEAN,
	P_AGE INTEGER,
	P_FIO VARCHAR(100),
	P_CONTACT_DATA VARCHAR(100))
RETURNS (
	ID INTEGER,
	NAME VARCHAR(100),
	SECOND_NAME VARCHAR(100),
	SURNAME VARCHAR(100),
	SEX VARCHAR(10),
	DOB DATE
)
AS
DECLARE VARIABLE V_DOB DATE;
DECLARE VARIABLE V_FIO VARCHAR(100);
DECLARE VARIABLE V_VAL VARCHAR(100);
BEGIN
	V_DOB = IIF(P_AGE IS NULL, 
				CAST('1900-01-01' AS DATE),
				DATEADD(-P_AGE-1 YEAR TO CURRENT_DATE));
	V_FIO = IIF(COALESCE(CHAR_LENGTH(P_FIO), 0) > 1, '%' || P_FIO || '%',  '%');
	V_VAL = IIF(COALESCE(CHAR_LENGTH(P_CONTACT_DATA), 0) > 3, '%' || P_CONTACT_DATA || '%',  NULL);
	
    FOR SELECT DISTINCT
    	p.ID,
    	p.NAME,
    	p.SECOND_NAME,
    	p.SURNAME, 
    	decode(p.SEX, TRUE, 'МУЖ.', 'ЖЕН.') SEX,
    	p.DOB
    FROM PERSON p
    LEFT JOIN CONTACT c ON c.PERSON_ID = p.ID
    LEFT JOIN CONTACT_TYPE t ON t.ID = c.CONTACT_TYPE_ID
    WHERE p.SEX = COALESCE(:P_SEX, p.SEX)
      AND p.DOB >= :V_DOB
      AND p.NAME || p.SECOND_NAME || p.SURNAME LIKE :V_FIO
      AND (c.VAL LIKE :V_VAL OR :V_VAL IS NULL)
    INTO :ID, :NAME, :SECOND_NAME, :SURNAME, :SEX, :DOB
    DO SUSPEND;
END^


CREATE OR ALTER PROCEDURE SP_ADD_PERSON (
	P_SURNAME VARCHAR(100),
	P_NAME VARCHAR(100),
	P_SECOND_NAME VARCHAR(100),
	P_SEX BOOLEAN ,
	P_DOB DATE)
RETURNS (
	P_ID INTEGER
)
AS
BEGIN
    INSERT INTO PERSON (SURNAME, NAME, SECOND_NAME, SEX, DOB)
    VALUES (:P_SURNAME, :P_NAME, :P_SECOND_NAME, :P_SEX, :P_DOB)
	RETURNING ID INTO :P_ID;

    SUSPEND;
END^


CREATE OR ALTER PROCEDURE SP_DEL_PERSON (
    P_ID INTEGER
) AS
BEGIN
    DELETE FROM CONTACT WHERE PERSON_ID = :P_ID;
    DELETE FROM PERSON WHERE ID = :P_ID;
END^


CREATE OR ALTER PROCEDURE SP_GET_TYPES RETURNS (
	ID INTEGER,
	NAME VARCHAR(100)
)
AS
BEGIN
    FOR SELECT ID, NAME 
    FROM CONTACT_TYPE 
    INTO :ID, :NAME
    DO SUSPEND;
END^


CREATE OR ALTER PROCEDURE SP_ADD_TYPE (P_NAME VARCHAR(100))
RETURNS (
	P_ID INTEGER
)
AS
BEGIN
    INSERT INTO CONTACT_TYPE (NAME)
    VALUES (:P_NAME)
	RETURNING ID INTO :P_ID;

    SUSPEND;
END^


CREATE OR ALTER PROCEDURE SP_DEL_TYPE (P_ID INTEGER)
AS
BEGIN
    DELETE FROM CONTACT_TYPE WHERE ID = :P_ID;
END^


CREATE OR ALTER PROCEDURE SP_GET_CONTACTS (P_PERSON_ID INTEGER)
RETURNS (
	ID INTEGER,
	VAL VARCHAR(100),
	NAME VARCHAR(100),
	CT_ID INTEGER
)
AS
BEGIN
    FOR SELECT c.ID, c.VAL, ct.NAME, ct.ID CT_ID 
    FROM CONTACT_TYPE  ct
    LEFT JOIN CONTACT c ON ct.ID = c.CONTACT_TYPE_ID
		AND c.PERSON_ID = :P_PERSON_ID
    INTO :ID, :VAL, :NAME, :CT_ID
    DO SUSPEND;
END^


CREATE OR ALTER PROCEDURE SP_ADD_CONTACT (
	P_PERSON_ID INTEGER,
	P_CONTACT_TYPE_ID INTEGER,
	P_VAL VARCHAR(100))
RETURNS (
	P_ID INTEGER
)
AS
BEGIN
    INSERT INTO CONTACT(VAL, PERSON_ID, CONTACT_TYPE_ID)
    VALUES (:P_VAL, :P_PERSON_ID, :P_CONTACT_TYPE_ID)
	RETURNING ID INTO :P_ID;

	SUSPEND;
END^


CREATE OR ALTER PROCEDURE SP_DEL_CONTACT (P_CONTACT_ID INTEGER)
AS
BEGIN
    DELETE FROM CONTACT WHERE ID = :P_CONTACT_ID;
END^


